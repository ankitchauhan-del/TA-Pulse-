function handleRoleListClick(e){
  const showAllLog = e.target.closest('[data-action="show-all-log"]');
  if (showAllLog){
    const id = showAllLog.dataset.id;
    const role = findRole(id);
    const listEl = document.querySelector(`[data-log-list="${id}"]`);
    listEl.innerHTML = (role.log||[]).map(logItemHTML).join('');
    showAllLog.remove();
    return;
  }

  const toggleAttn = e.target.closest('[data-action="toggle-attention"]');
  if (toggleAttn){
    const id = toggleAttn.dataset.id;
    const role = findRole(id);
    role.needsAttention = !role.needsAttention;
    toggleAttn.classList.toggle('is-active', role.needsAttention);
    const group = document.querySelector(`.role-group[data-id="${id}"]`);
    group.classList.toggle('is-flagged', role.needsAttention);
    renderKPIs();
    scheduleSaveRoles();
    return;
  }

  const addLog = e.target.closest('[data-action="add-log"]');
  if (addLog){
    const id = addLog.dataset.id;
    const input = document.querySelector(`[data-log-input="${id}"]`);
    const text = input.value.trim();
    if (!text) return;
    const role = findRole(id);
    role.log = role.log || [];
    role.log.unshift({ date: todayLabel(), text });
    input.value = '';
    const listEl = document.querySelector(`[data-log-list="${id}"]`);
    const visible = role.log.slice(0,2);
    listEl.innerHTML = visible.map(logItemHTML).join('');
    const rest = role.log.length - visible.length;
    let moreBtn = document.querySelector(`[data-action="show-all-log"][data-id="${id}"]`);
    if (rest > 0 && !moreBtn){
      moreBtn = document.createElement('button');
      moreBtn.className = 'log-more';
      moreBtn.dataset.action = 'show-all-log';
      moreBtn.dataset.id = id;
      moreBtn.textContent = `Show ${rest} earlier update${rest===1?'':'s'}`;
      listEl.insertAdjacentElement('afterend', moreBtn);
    } else if (moreBtn){
      moreBtn.textContent = `Show ${rest} earlier update${rest===1?'':'s'}`;
    }
    scheduleSaveRoles();
    return;
  }

  const delBtn = e.target.closest('[data-action="delete-role"]');
  if (delBtn){
    const id = delBtn.dataset.id;
    if (pendingDeleteId !== id){
      pendingDeleteId = id;
      delBtn.textContent = 'Click again to confirm';
      clearTimeout(pendingDeleteTimer);
      pendingDeleteTimer = setTimeout(() => {
        pendingDeleteId = null;
        if (delBtn.isConnected) delBtn.textContent = 'Delete role';
      }, 4000);
      return;
    }
    clearTimeout(pendingDeleteTimer);
    pendingDeleteId = null;
    state.roles = state.roles.filter(r => r.id !== id);
    scheduleSaveRoles();
    renderKPIs(); renderWaveform(); renderRoleList();
    return;
  }

  // Fallback: clicking the collapsed row (but not an input/select within it) expands/collapses detail
  const row = e.target.closest('.role-row');
  if (row && !e.target.closest('input,select,textarea,a')){
    row.closest('.role-group').classList.toggle('is-open');
  }
}

function handleRoleListInput(e){
  const el = e.target;
  const field = el.dataset.field;
  const id = el.dataset.id;
  if (!field || !id) return;
  const role = findRole(id);
  if (!role) return;

  if (field === 'title'){
    role.title = el.value;
    updateTitleView(role);
  } else if (['candidatesShared','r1Count','r2Count'].includes(field)){
    role[field] = Number(el.value) || 0;
    if (role.roster && role.roster.length){
      // A detailed roster snapshot exists from the original import, but there's no UI
      // to edit individual candidates anymore — once the person hand-edits the totals,
      // the donut should follow those numbers instead of silently keeping the old snapshot.
      role.roster = [];
    }
    updateStatDonut(role);
  } else if (['totalApprovedReqs','openPositions'].includes(field)){
    role[field] = Number(el.value) || 0;
    updateStatDonut(role);
  } else if (field === 'targetOfferDate'){
    role.targetOfferDate = el.value.trim() || null;
    updateDateBadge(role);
  } else if (field === 'sheetLink'){
    role.sourceSheets = makeSheetEntry(el.value, role.title);
    updateSheetLinkViews(role);
  } else if (field === 'offerCandidate'){
    role.offerCandidate = el.value;
    renderWaveform(); // refreshes the Offers in flight panel
  } else if (field === 'joiningDate'){
    role.joiningDate = el.value;
    renderWaveform();
  }
  scheduleSaveRoles();
}

// Refresh the little icon in the row + the pill in the detail panel after a link edit,
// without rebuilding the whole list (which would collapse the open row mid-typing).
function updateSheetLinkViews(role){
  const group = document.querySelector(`.role-group[data-id="${role.id}"]`);
  if (!group) return;
  const titleWrap = group.querySelector('.row-title');
  if (titleWrap){
    const oldIcon = titleWrap.querySelector('.sheet-link');
    if (oldIcon) oldIcon.remove();
    const iconHtml = sheetIconHTML(role);
    if (iconHtml) titleWrap.insertAdjacentHTML('beforeend', iconHtml);
  }
  const detail = group.querySelector('.role-detail');
  if (detail){
    const oldRow = detail.querySelector('.sheet-links-row');
    const newRowHtml = sheetLinksRowHTML(role);
    if (oldRow){
      if (newRowHtml){ oldRow.outerHTML = newRowHtml; }
      else { oldRow.remove(); }
    } else if (newRowHtml){
      const stats = detail.querySelector('.detail-stats-row');
      if (stats) stats.insertAdjacentHTML('afterend', newRowHtml);
    }
  }
}

function handleRoleListChange(e){
  const el = e.target;
  if (el.dataset.field === 'status' && el.tagName === 'SELECT'){
    const id = el.dataset.id;
    const role = findRole(id);
    role.status = el.value;
    updateStatusView(role);
    updateDateBadge(role);
    renderKPIs();
    renderWaveform(); // status change may add/remove this role from Offers in flight
    scheduleSaveRoles();
  } else if (el.dataset.field === 'offerSigned' && el.type === 'checkbox'){
    const role = findRole(el.dataset.id);
    if (role){
      role.offerSigned = el.checked;
      renderWaveform();
      scheduleSaveRoles();
    }
  }
}

