async function apiGet(endpoint){
  try{
    const res = await fetch(endpoint, { method:'GET' });
    if (!res.ok) return { found:false, value:null };
    const data = await res.json();
    if (data.value === null || data.value === undefined) return { found:false, value:null };
    return { found:true, value:data.value };
  }catch(e){
    return { found:false, value:null };
  }
}
async function apiSet(endpoint, value){
  try{
    const res = await fetch(endpoint, {
      method:'POST',
      headers:{'Content-Type':'application/json'},
      body: JSON.stringify({ value }),
    });
    return res.ok;
  }catch(e){
    return false;
  }
}

function scheduleSaveRoles(){
  if (apiAvailable === false){ setSyncStatus('unavailable'); return; }
  setSyncStatus('saving');
  clearTimeout(saveRolesTimer);
  saveRolesTimer = setTimeout(async () => {
    const ok = await apiSet(API_ROLES, state.roles);
    if (ok){ await touchLastUpdated(); setSyncStatus('saved'); }
    else setSyncStatus('error');
  }, 500);
}

function scheduleSaveNarrative(){
  if (apiAvailable === false){ setSyncStatus('unavailable'); return; }
  setSyncStatus('saving');
  clearTimeout(saveNarrativeTimer);
  saveNarrativeTimer = setTimeout(async () => {
    const ok = await apiSet(API_NARRATIVE, state.narrative);
    if (ok){ await touchLastUpdated(); setSyncStatus('saved'); }
    else setSyncStatus('error');
  }, 500);
}

async function touchLastUpdated(){
  state.narrative.lastUpdated = new Date().toISOString();
  await apiSet(API_NARRATIVE, state.narrative);
  renderLastUpdated();
}

function setSyncStatus(status){
  const el = document.getElementById('sync-status');
  if (!el) return;
  if (status === 'saving'){ el.textContent = 'Saving…'; }
  else if (status === 'saved'){ el.textContent = 'Synced'; }
  else if (status === 'error'){ el.textContent = 'Save failed — check connection'; }
  else if (status === 'unavailable'){ el.textContent = "Can't reach the database — check Vercel/Upstash setup"; }
  showToast(status);
}

let toastTimer = null;
function showToast(status){
  const toast = document.getElementById('toast');
  const text = document.getElementById('toast-text');
  if (!toast || !text) return;
  if (status === 'saving' || status === 'unavailable') return; // don't toast every keystroke, banner already covers this
  toast.classList.remove('is-error');
  if (status === 'saved'){ text.textContent = 'Saved'; }
  else if (status === 'error'){ text.textContent = "Couldn't save — will retry"; toast.classList.add('is-error'); }
  else return;
  toast.classList.add('is-visible');
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => toast.classList.remove('is-visible'), 1800);
}

// ===================== Init =====================
async function init(){
  await checkApi();

  const banner = document.getElementById('storage-banner');
  if (apiAvailable === false && banner){
    banner.style.display = 'flex';
    const bannerText = document.getElementById('storage-banner-text');
    if (bannerText) bannerText.innerHTML = "<strong>Can't reach the database.</strong> Check that the Upstash Redis storage integration is connected in your Vercel project (Storage tab) and redeploy.";
  }

  if (apiAvailable){
    let rolesRes = await apiGet(API_ROLES);
    if (!rolesRes.found){
      // Nothing saved yet anywhere -> first ever load, seed it once.
      state.roles = SEED_ROLES.map(r => ({ ...r }));
      await apiSet(API_ROLES, state.roles);
    } else {
      state.roles = rolesRes.value || [];
    }

    const narrRes = await apiGet(API_NARRATIVE);
    if (narrRes.found && narrRes.value){
      state.narrative = Object.assign({focus:'',progress:'',blockers:'',preparedBy:'',weekLabel:'',lastUpdated:null}, narrRes.value);
    } else {
      state.narrative.weekLabel = defaultWeekLabel();
      await apiSet(API_NARRATIVE, state.narrative);
    }
  } else {
    // API unreachable: populate from the seed so the page is still usable to look at,
    // but nothing will persist until the database connection is fixed.
    state.roles = SEED_ROLES.map(r => ({ ...r }));
    state.narrative.weekLabel = defaultWeekLabel();
  }
  if (!state.narrative.weekLabel) state.narrative.weekLabel = defaultWeekLabel();

  document.getElementById('loading').style.display = 'none';
  document.getElementById('app').style.display = 'block';

  renderNarrativeFields();
  renderLastUpdated();
  renderKPIs();
  renderWaveform();
  renderRoleList();
  bindStaticEvents();
  if (apiAvailable) startPolling();
  else setSyncStatus('unavailable');
}

function startPolling(){
  pollTimer = setInterval(async () => {
    if (document.hidden) return; // save quota while the tab isn't even visible
    const active = document.activeElement;
    const isTyping = active && (active.tagName === 'INPUT' || active.tagName === 'TEXTAREA' || active.tagName === 'SELECT');
    if (isTyping) return;
    if (document.getElementById('modal-overlay').classList.contains('is-open')) return;
    // Don't let a background refresh overwrite an in-progress drag, or clobber the
    // order while someone is actively editing (their unsaved reorder would vanish).
    if (document.querySelector('.role-group.is-dragging')) return;
    if (state.mode === 'edit') return;
    const rolesRes = await apiGet(API_ROLES);
    if (rolesRes.found) state.roles = rolesRes.value || [];
    const narrRes = await apiGet(API_NARRATIVE);
    if (narrRes.found && narrRes.value) state.narrative = Object.assign(state.narrative, narrRes.value);
    renderNarrativeFields();
    renderLastUpdated();
    renderKPIs();
    renderWaveform();
    renderRoleList();
  }, POLL_MS);
}

// ===================== KPIs =====================
function computeKPIs(){
  const roles = state.roles;
  const open = roles.filter(r => r.status === 'Open').length;
  const onHold = roles.filter(r => r.status === 'On hold').length;
  const submitted = roles.reduce((s,r) => s + (Number(r.candidatesShared)||0), 0);
  const interviewing = roles.reduce((s,r) => s + (Number(r.r1Count)||0) + (Number(r.r2Count)||0), 0);
  const attention = roles.filter(r => r.needsAttention || isOverdue(r)).length;
  const offers = roles.reduce((s,r) => {
    if (r.roster && r.roster.length) return s + r.roster.filter(c => c.offer).length;
    return s + (r.status === 'Offer stage' ? 1 : 0);
  }, 0);
  return { open, onHold, submitted, interviewing, attention, offers };
}

