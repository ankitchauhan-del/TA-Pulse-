// ===================== Role list =====================
function filteredRoles(){
  const q = state.searchQuery.trim().toLowerCase();
  return state.roles.filter(r => {
    if (state.specialFilter === 'interviewing'){
      if (((Number(r.r1Count)||0) + (Number(r.r2Count)||0)) <= 0) return false;
    } else if (state.specialFilter === 'attention'){
      if (!(r.needsAttention || isOverdue(r))) return false;
    } else if (state.filterStatus !== 'All' && r.status !== state.filterStatus){
      return false;
    }
    if (!q) return true;
    return r.title.toLowerCase().includes(q);
  });
}

