function syncKpiActiveState(){
  document.querySelectorAll('.kpi-card').forEach(card => {
    const type = card.dataset.kpi;
    let active = false;
    if (state.specialFilter === 'interviewing' && type === 'interviewing') active = true;
    else if (state.specialFilter === 'attention' && type === 'attention') active = true;
    else if (!state.specialFilter){
      if (type === 'open' && state.filterStatus === 'Open') active = true;
      if (type === 'onhold' && state.filterStatus === 'On hold') active = true;
      if (type === 'offers' && state.filterStatus === 'Offer stage') active = true;
      if (type === 'submitted' && state.filterStatus === 'All' && !state.searchQuery) active = true;
    }
    card.classList.toggle('is-selected', active);
  });
}

function applyKpiFilter(type){
  state.searchQuery = '';
  document.getElementById('search-input').value = '';

  if (type === 'open'){
    state.filterStatus = 'Open'; state.specialFilter = null;
  } else if (type === 'onhold'){
    state.filterStatus = 'On hold'; state.specialFilter = null;
  } else if (type === 'offers'){
    state.filterStatus = 'Offer stage'; state.specialFilter = null;
  } else if (type === 'interviewing'){
    state.filterStatus = 'All'; state.specialFilter = 'interviewing';
  } else if (type === 'attention'){
    state.filterStatus = 'All'; state.specialFilter = 'attention';
  } else { // 'submitted' — spans every role, so just clear back to everything
    state.filterStatus = 'All'; state.specialFilter = null;
  }

  document.querySelectorAll('#filter-chips .chip').forEach(c => {
    c.classList.toggle('is-active', !state.specialFilter && c.dataset.status === state.filterStatus);
  });
  renderRoleList();
  syncKpiActiveState();
  document.getElementById('section-count').scrollIntoView({ behavior:'smooth', block:'start' });
}

