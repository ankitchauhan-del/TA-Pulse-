// ===================== Helpers =====================
function escapeHtml(str){
  if (str === null || str === undefined) return '';
  return String(str)
    .replaceAll('&','&amp;').replaceAll('<','&lt;').replaceAll('>','&gt;')
    .replaceAll('"','&quot;').replaceAll("'",'&#39;');
}

function uid(){
  if (window.crypto && window.crypto.randomUUID) return crypto.randomUUID();
  return 'r-' + Date.now() + '-' + Math.floor(Math.random()*100000);
}

function parseFuzzyDate(str){
  if (!str) return null;
  const cleaned = String(str).replace(/(\d+)(st|nd|rd|th)\b/gi, '$1');
  const d = new Date(cleaned);
  return isNaN(d.getTime()) ? null : d;
}

function isOverdue(role){
  if (role.status === 'Closed') return false;
  const d = parseFuzzyDate(role.targetOfferDate);
  if (!d) return false;
  const today = new Date();
  today.setHours(0,0,0,0);
  return d < today;
}

function todayLabel(){
  const d = new Date();
  return d.toLocaleDateString('en-US', { day:'numeric', month:'short' });
}

function timeAgoLabel(iso){
  if (!iso) return '—';
  const then = new Date(iso).getTime();
  const now = Date.now();
  const diffSec = Math.round((now - then)/1000);
  if (diffSec < 30) return 'just now';
  if (diffSec < 90) return '1 min ago';
  if (diffSec < 3600) return Math.round(diffSec/60) + ' min ago';
  if (diffSec < 7200) return '1 hr ago';
  if (diffSec < 86400) return Math.round(diffSec/3600) + ' hrs ago';
  const then_d = new Date(iso);
  return then_d.toLocaleDateString('en-US', { day:'numeric', month:'short', hour:'numeric', minute:'2-digit' });
}

function defaultWeekLabel(){
  const now = new Date();
  const day = now.getDay(); // 0 sun .. 6 sat
  const diffToMonday = (day === 0 ? -6 : 1 - day);
  const monday = new Date(now); monday.setDate(now.getDate() + diffToMonday);
  const friday = new Date(monday); friday.setDate(monday.getDate() + 4);
  const fmt = (d) => d.toLocaleDateString('en-US', { day:'numeric', month:'short' });
  return fmt(monday) + '–' + fmt(friday) + ', ' + friday.getFullYear();
}

function parseNames(raw){
  if (!raw) return [];
  return raw.split(',').map(s => s.trim()).filter(Boolean);
}

function statusBadgeClass(status){
  if (status === 'Open') return 'badge-open';
  if (status === 'On hold') return 'badge-hold';
  if (status === 'Offer stage') return 'badge-offer';
  if (status === 'Closed') return 'badge-closed';
  return 'badge-hold';
}

